import { NextRequest, NextResponse } from "next/server";
import { createSupabaseAdmin } from "@/lib/supabase-admin";
import {
  isValidShortCode,
  generateRawToken,
  TABLE_CONTEXT_COOKIE,
  GUEST_DEVICE_TOKEN_COOKIE,
  type TableContextPayload,
} from "@/lib/table-qr";
import { getV2TemplateForWebsite } from "@/lib/website-v2-theme";

interface Props {
  params: Promise<{ code: string }>;
}

export async function GET(request: NextRequest, { params }: Props) {
  const { code } = await params;

  if (!isValidShortCode(code)) {
    return new NextResponse(
      renderErrorHtml("Invalid QR Code", "The scanned QR code is malformed or invalid."),
      { status: 400, headers: { "Content-Type": "text/html; charset=utf-8" } }
    );
  }

  const admin = createSupabaseAdmin();

  // 1. Look up active QR redirect code
  const { data: qrRecord, error: qrError } = await admin
    .from("qr_redirect_codes")
    .select("id, code, target_type, business_id, table_id, is_active")
    .eq("code", code)
    .maybeSingle();

  if (qrError || !qrRecord || !qrRecord.is_active) {
    return new NextResponse(
      renderErrorHtml(
        "QR Code Inactive or Expired",
        "This QR code is no longer active. It may have been replaced or regenerated by restaurant staff. Please request a new code from your server."
      ),
      { status: 404, headers: { "Content-Type": "text/html; charset=utf-8" } }
    );
  }

  // 2. Fetch business details including organizer_id
  const { data: business, error: bizError } = await admin
    .from("businesses")
    .select("id, name, slug, status, table_ordering_mode, organizer_id")
    .eq("id", qrRecord.business_id)
    .maybeSingle();

  if (bizError || !business || business.status !== "active") {
    return new NextResponse(
      renderErrorHtml(
        "Restaurant Unavailable",
        "This restaurant is currently inactive or unavailable."
      ),
      { status: 404, headers: { "Content-Type": "text/html; charset=utf-8" } }
    );
  }

  // Check if table ordering is completely disabled
  if (business.table_ordering_mode === "disabled") {
    return new NextResponse(
      renderErrorHtml(
        "Table Ordering Disabled",
        "Table ordering is currently disabled for this restaurant. Please speak to your server for assistance."
      ),
      { status: 403, headers: { "Content-Type": "text/html; charset=utf-8" } }
    );
  }

  // 3. Resolve the authoritative tenant website & menu page
  const { data: website } = await admin
    .from("tenant_websites")
    .select("id, slug, status, metadata")
    .eq("tenant_id", business.organizer_id)
    .eq("status", "published")
    .order("created_at", { ascending: true })
    .limit(1)
    .maybeSingle();

  if (!website) {
    return new NextResponse(
      renderErrorHtml(
        "Menu Unavailable",
        "This restaurant has not published their website or menu yet. Please speak to your server for assistance."
      ),
      { status: 404, headers: { "Content-Type": "text/html; charset=utf-8" } }
    );
  }

  const siteSlug = website.slug;
  const url = new URL(request.url);
  const baseUrl = `${url.protocol}//${url.host}`;

  // Determine whether the restaurant has a dedicated published /menu page
  let menuPath = `/site/${siteSlug}`;
  const { data: menuPageRow } = await admin
    .from("website_pages")
    .select("id, slug, status")
    .eq("website_id", website.id)
    .eq("slug", "menu")
    .maybeSingle();

  if (menuPageRow) {
    if (menuPageRow.status === "published") {
      menuPath = `/site/${siteSlug}/menu`;
    }
  } else {
    const v2Template = website.metadata ? getV2TemplateForWebsite(website.metadata) : null;
    const hasV2Menu = v2Template?.pages?.some((p) => p.slug === "menu");
    if (hasV2Menu) {
      menuPath = `/site/${siteSlug}/menu`;
    }
  }

  // 4. Handle Menu QR (General Point-of-Entry)
  if (qrRecord.target_type === "menu") {
    const destination = new URL(menuPath, baseUrl);
    destination.searchParams.set("from_qr", "menu");
    const response = NextResponse.redirect(destination);
    return response;
  }

  // 5. Handle Table QR
  if (!qrRecord.table_id) {
    return new NextResponse(
      renderErrorHtml("Table Not Found", "No table is associated with this QR code."),
      { status: 404, headers: { "Content-Type": "text/html; charset=utf-8" } }
    );
  }

  const { data: table, error: tableError } = await admin
    .from("business_tables")
    .select("id, label, is_active")
    .eq("id", qrRecord.table_id)
    .eq("business_id", business.id)
    .maybeSingle();

  if (tableError || !table) {
    return new NextResponse(
      renderErrorHtml("Table Not Found", "The table linked to this QR code could not be found."),
      { status: 404, headers: { "Content-Type": "text/html; charset=utf-8" } }
    );
  }

  if (!table.is_active) {
    return new NextResponse(
      renderErrorHtml(
        "Table Inactive",
        `Table "${table.label}" is currently marked inactive by restaurant staff.`
      ),
      { status: 403, headers: { "Content-Type": "text/html; charset=utf-8" } }
    );
  }

  // Destination URL pointing directly to the restaurant's menu scoped to this table
  const destination = new URL(menuPath, baseUrl);
  destination.searchParams.set("table", table.id);
  destination.searchParams.set("table_label", table.label);
  destination.searchParams.set("qr_code", code);

  const response = NextResponse.redirect(destination);

  // Set table context cookie (secure in production, Lax, accessible to client & server)
  const contextPayload: TableContextPayload = {
    businessId: business.id,
    organizerId: business.organizer_id,
    tableId: table.id,
    tableLabel: table.label,
    qrCode: code,
    tableOrderingMode: business.table_ordering_mode || "order_pay_later",
    timestamp: Date.now(),
  };
  response.cookies.set(TABLE_CONTEXT_COOKIE, JSON.stringify(contextPayload), {
    path: "/",
    httpOnly: false,
    sameSite: "lax",
    secure: process.env.NODE_ENV === "production",
    maxAge: 60 * 60 * 24, // 24 hours
  });

  // Ensure persistent guest device token exists on client for pending order caps
  const existingGuestToken = request.cookies.get(GUEST_DEVICE_TOKEN_COOKIE)?.value;
  if (!existingGuestToken) {
    const rawToken = generateRawToken(32);
    response.cookies.set(GUEST_DEVICE_TOKEN_COOKIE, rawToken, {
      path: "/",
      httpOnly: false,
      sameSite: "lax",
      secure: process.env.NODE_ENV === "production",
      maxAge: 60 * 60 * 24 * 30, // 30 days
    });
  }

  return response;
}

